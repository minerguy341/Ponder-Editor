// E1 model audit (gate G3): every ported entity model's cuboids (origin, size, texOffs, grow, mirror) and part poses must equal
// the vanilla layer definition in the decompiled Java (Yeet-Masta/MCP-1.21 mirror, cached in tools/.cache/e1-java).
//   node tools/e1-model-audit.mjs            prints ENTITY_MODELS_OK on success (exit 0), otherwise the mismatches (exit 1)
//
// The Java side is parsed from the `createBodyLayer` / `createBodyMesh` / `createFurLayer` statements (addOrReplaceChild with a
// literal part name, CubeListBuilder chains with texOffs/addBox, PartPose.offset/offsetAndRotation/ZERO). The TypeScript side is
// the bundled result of tools/e1-layers-dump.ts. Blaze's rods are generated by Java loops: their expected poses are the loop
// formulas of BlazeModel.createBodyLayer, transcribed below with the line numbers of the decompiled source.
import { mkdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = join(ROOT, 'tools', '.cache', 'e1');
const JAVA_DIR = join(CACHE, 'java');
const MIRROR = 'https://raw.githubusercontent.com/Yeet-Masta/MCP-1.21/main/src/main/java/net/minecraft/client/model';
const JAVA_FILES = ['ParrotModel.java', 'MinecartModel.java', 'BlazeModel.java', 'SheepModel.java', 'SheepFurModel.java', 'QuadrupedModel.java'];

mkdirSync(JAVA_DIR, { recursive: true });
for (const f of JAVA_FILES) {
  const p = join(JAVA_DIR, f);
  if (!existsSync(p)) {
    const res = await fetch(`${MIRROR}/${f}`);
    if (!res.ok) throw new Error(`fetch ${f}: HTTP ${res.status}`);
    writeFileSync(p, await res.text());
  }
}
const java = Object.fromEntries(JAVA_FILES.map((f) => [f, readFileSync(join(JAVA_DIR, f), 'utf8')]));

// ------------------------------------------------------------------------------------------------ TypeScript side (bundled)
const bundle = join(CACHE, 'layers-dump.mjs');
await build({
  entryPoints: [join(ROOT, 'tools', 'e1-layers-dump.ts')],
  bundle: true, platform: 'node', format: 'esm', outfile: bundle, logLevel: 'error',
});
const { dumpLayers } = await import(`${bundle}?v=${Date.now()}`);
const ts = dumpLayers();

// ------------------------------------------------------------------------------------------------ Java side
function stripComments(s) {
  return s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

/** body of the method whose signature contains `sig` (brace matched) */
function methodBody(src, sig) {
  const i = src.indexOf(sig);
  if (i < 0) throw new Error(`signature not found: ${sig}`);
  const open = src.indexOf('{', i);
  let depth = 0;
  for (let k = open; k < src.length; k++) {
    if (src[k] === '{') depth++;
    else if (src[k] === '}') { depth--; if (depth === 0) return src.slice(open + 1, k); }
  }
  throw new Error(`unterminated ${sig}`);
}

/** split at `sep` where parentheses and braces are balanced */
function splitTop(s, sep = ',') {
  const out = [];
  let depth = 0, cur = '';
  for (const ch of s) {
    if (ch === '(' || ch === '{') depth++;
    if (ch === ')' || ch === '}') depth--;
    if (ch === sep && depth === 0) { out.push(cur.trim()); cur = ''; } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

/** the text inside the parentheses that follow `open` (which ends just before the '(') */
function argsAt(s, openIdx) {
  let depth = 0;
  for (let k = openIdx; k < s.length; k++) {
    if (s[k] === '(') depth++;
    else if (s[k] === ')') { depth--; if (depth === 0) return s.slice(openIdx + 1, k); }
  }
  throw new Error(`unbalanced: ${s}`);
}

const num = (e) => {
  const t = e.trim().replace(/\(float\)/g, '').replace(/(\d+\.?\d*(?:e-?\d+)?)[Ff]\b/g, '$1');
  return Function('Math', `return (${t});`)(Math);
};

/** CubeListBuilder chain: [{ texOffs: [u,v] } | { box: { x,y,z,w,h,d, grow } }] */
function parseBuilder(expr, builders) {
  const e = expr.trim();
  if (/^\w+$/.test(e)) {
    if (!builders[e]) throw new Error(`unknown builder ${e}`);
    return parseBuilder(builders[e], builders);
  }
  const cube = { u: 0, v: 0, x: 0, y: 0, z: 0, w: 0, h: 0, d: 0, grow: [0, 0, 0], mirror: false };
  const cubes = [];
  let i = 0;
  while (true) {
    const m = /\.(texOffs|addBox|mirror)\(/g;
    m.lastIndex = i;
    const r = m.exec(e);
    if (!r) break;
    const open = r.index + r[0].length - 1;
    const args = argsAt(e, open);
    i = open + args.length + 2;
    if (r[1] === 'texOffs') {
      const [u, v] = splitTop(args).map(num);
      cube.u = u; cube.v = v;
    } else if (r[1] === 'mirror') {
      cube.mirror = true;
    } else {
      const parts = splitTop(args);
      const [x, y, z, w, h, d] = parts.slice(0, 6).map(num);
      let grow = [0, 0, 0];
      const gExpr = parts[6];
      if (gExpr && gExpr !== 'NONE' && !/CubeDeformation\.NONE/.test(gExpr)) {
        const g = /new CubeDeformation\((.*)\)/.exec(gExpr);
        if (!g) throw new Error(`unknown deformation ${gExpr}`);
        const gv = num(g[1]);
        grow = [gv, gv, gv];
      }
      cubes.push({ ...cube, x, y, z, w, h, d, grow: [...grow] });
    }
  }
  return cubes;
}

function parsePose(expr) {
  const e = expr.trim();
  if (e === 'PartPose.ZERO') return { x: 0, y: 0, z: 0, xRot: 0, yRot: 0, zRot: 0 };
  const m = /^PartPose\.(offset|offsetAndRotation)\(/.exec(e);
  if (!m) throw new Error(`unknown pose ${e}`);
  const v = splitTop(argsAt(e, m[0].length - 1)).map(num);
  if (m[1] === 'offset') return { x: v[0], y: v[1], z: v[2], xRot: 0, yRot: 0, zRot: 0 };
  return { x: v[0], y: v[1], z: v[2], xRot: v[3], yRot: v[4], zRot: v[5] };
}

/**
 * Applies the statements of a createBodyLayer-like body to `tree` (Map path -> {pose, cubes}). `vars` maps the Java variable
 * names of PartDefinition locals to their part path ('' = root).
 */
function applyBody(tree, body, subs) {
  let text = stripComments(body);
  for (const [k, v] of Object.entries(subs)) text = text.replace(new RegExp(k, 'g'), v);
  text = text.replace(/\s+/g, ' ');
  const builders = {};
  const vars = { partdefinition: '' };
  for (const stmt0 of text.split(';')) {
    const stmt = stmt0.trim();
    if (!stmt) continue;
    let m;
    if ((m = /^CubeListBuilder (\w+) = (.*)$/.exec(stmt))) { builders[m[1]] = m[2]; continue; }
    if ((m = /^PartDefinition (\w+) = (\w+)\.addOrReplaceChild\(/.exec(stmt))) {
      const parentPath = vars[m[2]] ?? null;
      if (parentPath === null) continue;
      const args = splitTop(argsAt(stmt, stmt.indexOf('(', m[0].length - 1)));
      const name = args[0].replace(/"/g, '');
      const path = parentPath ? `${parentPath}/${name}` : name;
      vars[m[1]] = path;
      tree.set(path, { pose: parsePose(args[2]), cubes: parseBuilder(args[1], builders) });
      continue;
    }
    if ((m = /^(\w+)\.addOrReplaceChild\(/.exec(stmt))) {
      const parentPath = vars[m[1]];
      if (parentPath === undefined) continue; // e.g. loops with computed names (blaze) are handled separately
      const args = splitTop(argsAt(stmt, stmt.indexOf('(')));
      if (!/^"\w+"$/.test(args[0])) continue;
      const name = args[0].replace(/"/g, '');
      const path = parentPath ? `${parentPath}/${name}` : name;
      tree.set(path, { pose: parsePose(args[2]), cubes: parseBuilder(args[1], builders) });
    }
  }
  return tree;
}

function javaLayer(file, sig, subs = {}, into = new Map()) {
  return applyBody(into, methodBody(java[file], sig), subs);
}

// Java expectations per layer, flattened to the same path keys as the TS dump
const expected = {};
expected.parrot = javaLayer('ParrotModel.java', 'public static LayerDefinition createBodyLayer()');
expected.minecart = javaLayer('MinecartModel.java', 'public static LayerDefinition createBodyLayer()');
expected.sheep = (() => {
  // SheepModel.createBodyLayer: QuadrupedModel.createBodyMesh(12, NONE) then the head/body overrides
  const subs = { p_170865_: '12', p_170866_: 'NONE' };
  const t = javaLayer('QuadrupedModel.java', 'public static MeshDefinition createBodyMesh(', subs);
  return javaLayer('SheepModel.java', 'public static LayerDefinition createBodyLayer()', subs, t);
})();
expected.sheepFur = javaLayer('SheepFurModel.java', 'public static LayerDefinition createFurLayer()');
expected.blaze = (() => {
  const t = javaLayer('BlazeModel.java', 'public static LayerDefinition createBodyLayer()');
  // BlazeModel.java: the rods are generated by loops (addOrReplaceChild(getPartName(i), cubelistbuilder, PartPose.offset(...)))
  // with the single builder `cubelistbuilder` (texOffs(0, 16).addBox(0, 0, 0, 2, 8, 2)); the loop poses are transcribed below.
  const body = methodBody(java['BlazeModel.java'], 'public static LayerDefinition createBodyLayer()').replace(/\s+/g, ' ');
  const rb = /CubeListBuilder cubelistbuilder = (CubeListBuilder\.create\(\)[^;]*);/.exec(body);
  if (!rb) throw new Error('blaze rod builder not found');
  const rod = parseBuilder(rb[1], {});
  const poses = [];
  let f = 0;
  for (let i = 0; i < 4; i++) { poses.push([Math.cos(f) * 9, -2 + Math.cos((i * 2) * 0.25), Math.sin(f) * 9]); f++; }
  f = Math.PI / 4;
  for (let j = 4; j < 8; j++) { poses.push([Math.cos(f) * 7, 2 + Math.cos((j * 2) * 0.25), Math.sin(f) * 7]); f++; }
  f = 0.47123894;
  for (let k = 8; k < 12; k++) { poses.push([Math.cos(f) * 5, 11 + Math.cos(k * 1.5 * 0.5), Math.sin(f) * 5]); f++; }
  const out = new Map();
  out.set('head', t.get('head'));
  poses.forEach(([x, y, z], i) => out.set(`part${i}`, { pose: { x, y, z, xRot: 0, yRot: 0, zRot: 0 }, cubes: rod, loop: true }));
  return out;
})();

// ------------------------------------------------------------------------------------------------ comparison
function flatten(node, prefix = '', out = new Map()) {
  for (const p of node.children ?? []) {
    const path = prefix ? `${prefix}/${p.name}` : p.name;
    out.set(path, { pose: p.pose, cubes: p.cubes.map((c) => ({ u: c.u, v: c.v, x: c.x, y: c.y, z: c.z, w: c.w, h: c.h, d: c.d, grow: c.grow, mirror: c.mirror })) });
    flatten(p, path, out);
  }
  return out;
}

const problems = [];
let parts = 0, cubesChecked = 0;
const TOL = 1e-4;
const near = (a, b, tol = TOL) => Math.abs(a - b) <= tol;

function compareLayer(name, tsRoot, javaTree) {
  const tsFlat = flatten(tsRoot);
  const keys = new Set([...tsFlat.keys(), ...javaTree.keys()]);
  for (const key of keys) {
    const a = tsFlat.get(key);
    const b = javaTree.get(key);
    if (!a) { problems.push(`${name}/${key}: missing in TypeScript`); continue; }
    if (!b) { problems.push(`${name}/${key}: not in the Java layer`); continue; }
    parts++;
    const ptol = b.loop ? 2e-3 : TOL;
    for (const ax of ['x', 'y', 'z', 'xRot', 'yRot', 'zRot']) {
      if (!near(a.pose[ax], b.pose[ax], ptol)) problems.push(`${name}/${key} pose.${ax}: ts ${a.pose[ax]} java ${b.pose[ax]}`);
    }
    if (a.cubes.length !== b.cubes.length) { problems.push(`${name}/${key}: ${a.cubes.length} cubes ts, ${b.cubes.length} java`); continue; }
    a.cubes.forEach((c, i) => {
      const d = b.cubes[i];
      cubesChecked++;
      for (const k of ['u', 'v', 'x', 'y', 'z', 'w', 'h', 'd']) {
        if (c[k] !== d[k]) problems.push(`${name}/${key}#${i} ${k}: ts ${c[k]} java ${d[k]}`);
      }
      for (let g = 0; g < 3; g++) if (!near(c.grow[g], d.grow[g])) problems.push(`${name}/${key}#${i} grow[${g}]: ts ${c.grow[g]} java ${d.grow[g]}`);
      if (!!c.mirror !== !!d.mirror) problems.push(`${name}/${key}#${i} mirror`);
    });
  }
}

// self-test: the comparator must reject a corrupted cuboid (E1_AUDIT_SELFTEST=1 shifts the parrot body by one pixel)
if (process.env.E1_AUDIT_SELFTEST) {
  const body = ts.parrot.children.find((c) => c.name === 'body');
  body.cubes[0].x += 1;
}

/** the TypeScript dump has the root part as the layer root; the Java side is a flat path map */
for (const name of ['parrot', 'minecart', 'blaze', 'sheep', 'sheepFur']) {
  compareLayer(name, ts[name], expected[name]);
}

if (process.env.E1_AUDIT_SELFTEST) {
  if (problems.length === 0) { console.log('SELFTEST_FAILED: corrupted cuboid not detected'); process.exitCode = 1; }
  else { console.log(`SELFTEST_OK: corrupted cuboid detected (${problems.length} mismatch)`); }
  process.exit();
}

if (problems.length) {
  console.log(problems.slice(0, 40).join('\n'));
  console.log(`ENTITY_MODELS_FAILED ${problems.length} mismatches`);
  process.exitCode = 1;
} else {
  console.log(`checked ${parts} parts, ${cubesChecked} cuboids across parrot, minecart, blaze, sheep, sheep fur`);
  console.log('ENTITY_MODELS_OK');
}
