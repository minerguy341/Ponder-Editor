#!/usr/bin/env node
// Generates src/render/create/common/partialModels.ts from Create's AllPartialModels.java (tag mc1.21.1-6.0.10).
// Only model ids (names) are emitted - no Create assets. Usage: node tools/b-gen-partials.mjs
import fs from 'node:fs';
import path from 'node:path';
import { CREATE_TAG, createFile } from './b-lib.mjs';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = await createFile('src/main/java/com/simibubi/create/AllPartialModels.java');

const entries = [];
for (const m of src.matchAll(/\b([A-Z][A-Z0-9_]*[A-Za-z0-9]?)\s*=\s*(block|entity)\("([^"]+)"\)/g)) entries.push({ name: m[1], kind: m[2], p: m[3] });
const seen = new Set();
const lines = [];
for (const e of entries) {
  if (seen.has(e.name)) continue;
  seen.add(e.name);
  lines.push(`  ${e.name}: 'create:${e.kind}/${e.p}',`);
}

const out = `// GENERATED by tools/b-gen-partials.mjs from Create ${CREATE_TAG} AllPartialModels.java - do not edit.
// Model ids (names only) of Create's PartialModels, usable with getPartial(ctx, PARTIAL.SHAFT_HALF).
import type { Direction } from '../../../contract';

export const PARTIAL = {
${lines.join('\n')}
} as const;

export type DyeColorName = 'white' | 'orange' | 'magenta' | 'light_blue' | 'yellow' | 'lime' | 'pink' | 'gray' | 'light_gray' | 'cyan' | 'purple' | 'blue' | 'brown' | 'green' | 'red' | 'black';
export const DYE_COLORS: readonly DyeColorName[] = ['white', 'orange', 'magenta', 'light_blue', 'yellow', 'lime', 'pink', 'gray', 'light_gray', 'cyan', 'purple', 'blue', 'brown', 'green', 'red', 'black'];

/** AllPartialModels.DYED_VALVE_HANDLES.get(color) */
export function dyedValveHandle(color: DyeColorName): string { return \`create:block/\${color}_valve_handle\`; }
/** AllPartialModels.TOOLBOX_LIDS.get(color) */
export function toolboxLid(color: DyeColorName): string { return \`create:block/toolbox/lid/\${color}\`; }
/** AllPartialModels.METAL_GIRDER_BRACKETS.get(d) (horizontal d) */
export function metalGirderBracket(d: Direction): string { return \`create:block/metal_girder/bracket_\${d}\`; }
/** AllPartialModels.FACTORY_PANEL_ARROWS/LINES/DOTTED.get(d) (horizontal d) */
export function factoryPanelArrow(d: Direction): string { return \`create:block/factory_gauge/connections/arrow_\${d}\`; }
export function factoryPanelLine(d: Direction): string { return \`create:block/factory_gauge/connections/line_\${d}\`; }
export function factoryPanelDotted(d: Direction): string { return \`create:block/factory_gauge/connections/dotted_\${d}\`; }
/** AllPartialModels.CONTRAPTION_CONTROLS_INDICATOR.get(i), i in 0..7 */
export function contraptionControlsIndicator(i: number): string { return \`create:block/contraption_controls/indicator_\${i}\`; }
/** AllPartialModels.FOLDING_DOORS: path is 'andesite_door' | 'copper_door' */
export function foldingDoor(path: string, side: 'left' | 'right'): string { return \`create:block/\${path}/fold_\${side}\`; }
/** AllPartialModels.PIPE_ATTACHMENTS: component = lower-case ComponentPartials name (rim, drain, ...) */
export function pipeAttachment(component: string, d: Direction): string { return \`create:block/fluid_pipe/\${component}/\${d}\`; }
/** AllPartialModels.GANTRY_SHAFTS key name(): part is 'start' | 'middle' | 'end' | 'single' */
export function gantryShaft(part: string, powered: boolean, flipped: boolean): string {
  if (!(flipped || powered)) return \`create:block/gantry_shaft/block_\${part}\`;
  return \`create:block/gantry_shaft_\${part}\${powered ? '_powered' : ''}\${flipped ? '_flipped' : ''}\`;
}
`;
fs.writeFileSync(path.join(root, 'src/render/create/common/partialModels.ts'), out);
console.log(`wrote partialModels.ts with ${lines.length} partials`);
