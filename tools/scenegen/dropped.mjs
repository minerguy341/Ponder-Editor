// Dropped-call audit runner (C1 gate G8). Compiles every registered scene with the audit recorder on (drops.mjs), classifies each
// recorded event (dropped-classes.mjs) and writes tools/scenegen/DROPPED.md. Used by `report.mjs --dropped`.
import fs from 'node:fs';
import path from 'node:path';
import { setup, compileScene, ROOT } from './convert.mjs';
import { AUDIT } from './drops.mjs';
import { classify, CLASS_TEXT } from './dropped-classes.mjs';

export async function runDropAudit({ log = () => {} } = {}) {
  const env = await setup({ log });
  AUDIT.entries.length = 0;
  for (const g of env.groups) {
    try {
      compileScene(env, g, env.lang);
    } catch (e) {
      throw new Error(`scene ${g.id} failed during the drop audit: ${e.message}`);
    }
  }
  const entries = AUDIT.entries.slice();
  const result = classify(entries);
  return { entries, ...result, scenes: env.groups.length };
}

const esc = (s) => String(s).replace(/\|/g, '\\|');

export function renderDroppedMd(res) {
  const out = [];
  out.push('# Dropped calls (generated by `node tools/scenegen/report.mjs --dropped`; do not edit)');
  out.push('');
  out.push('Every call the converter accepts without turning it into a scene op (stub class or method, host method that emits nothing, block-entity class the converter cannot decide, a no-op override, a note) is recorded per scene and classified here.');
  out.push('Classes: `cosmetic` (rendering/audio/debug only), `metadata` (scene fields: title, keyframes), `getter` (returns a handle, no state), `link-binding` (binds an element link; the element itself is emitted with its `out` id), `legit-empty` (Java also does nothing: the instanceof test fails, the selection holds no matching block, or the value already equals the requested one; each case is listed below with its evidence), `state` (state-affecting and visible: must be zero).');
  out.push('');
  out.push(`Totals: ${res.entries.length} recorded events over ${res.scenes} scenes; ${res.byClass.size ? [...res.byClass].map(([c, n]) => `${c} ${n}`).join(', ') : 'none'}; unclassified ${res.unclassified.length}; state-affecting ${res.state.length}.`);
  out.push('');
  out.push('## Classes');
  out.push('');
  out.push('| class | meaning |');
  out.push('|---|---|');
  for (const [c, t] of Object.entries(CLASS_TEXT)) out.push(`| \`${c}\` | ${esc(t)} |`);
  out.push('');
  out.push('## Dropped methods (kind, owner.method): count, scenes, class, justification');
  out.push('');
  out.push('| kind | owner.method | count | scenes | class | justification |');
  out.push('|---|---|---:|---:|---|---|');
  for (const g of res.groups) out.push(`| ${g.kind} | \`${esc(g.owner)}.${esc(g.method)}\` | ${g.count} | ${g.scenes.size} | ${g.cls} | ${esc(g.why)} |`);
  out.push('');
  out.push('## Unclassified entries (must be empty)');
  out.push('');
  if (res.unclassified.length) for (const u of res.unclassified.slice(0, 200)) out.push(`- ${u.scene} ${u.where} ${u.kind} ${u.owner}.${u.method} ${esc(u.detail)}`);
  else out.push('none');
  out.push('');
  out.push('## State-affecting entries (must be empty)');
  out.push('');
  if (res.state.length) for (const u of res.state.slice(0, 200)) out.push(`- ${u.scene} ${u.where} ${u.kind} ${u.owner}.${u.method} ${esc(u.detail)}`);
  else out.push('none');
  out.push('');
  out.push('## Per scene');
  out.push('');
  out.push('| scene | events | state | unclassified |');
  out.push('|---|---:|---:|---:|');
  for (const s of res.perScene) out.push(`| ${s.scene} | ${s.n} | ${s.state} | ${s.unclassified} |`);
  out.push('');
  return out.join('\n');
}

export function writeDroppedMd(res) {
  const file = path.join(ROOT, 'tools/scenegen/DROPPED.md');
  fs.writeFileSync(file, renderDroppedMd(res));
  return file;
}
