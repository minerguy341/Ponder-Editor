/** A sprite stand-in with an explicit pixel grid (alpha test + uv math). */
export function fakeSprite(id: string, w = 16, h = 16, kind: SpriteLike['kind'] = 'solid', alpha?: (x: number, y: number) => number, atlasSize = 1024): SpriteLike {
  const px = new Uint8ClampedArray(w * h * 4);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) { const o = (y * w + x) * 4; px[o] = 200; px[o + 1] = 100; px[o + 2] = 50; px[o + 3] = alpha ? alpha(x, y) : 255; }
  // each sprite owns a distinct 0.1-wide column so uv values are easy to assert
  const n = [...id].reduce((a, c) => a + c.charCodeAt(0), 0) % 8;
  const u0 = n * 0.1, v0 = 0, u1 = u0 + 0.1, v1 = 0.1;
  return {
    id, w, h, u0, v0, u1, v1, atlasSize, kind, frames: [px],
    getU(f16: number) { return u0 + (u1 - u0) * (f16 / 16); },
    getV(f16: number) { return v0 + (v1 - v0) * (f16 / 16); },
  };
}

export function spriteSource(overrides: Record<string, SpriteLike> = {}): SpriteSource & { made: Map<string, SpriteLike> } {
  const made = new Map<string, SpriteLike>(Object.entries(overrides));
  return {
    made,
    sprite(id: string) {
      let s = made.get(id);
      if (!s) { s = fakeSprite(id); made.set(id, s); }
      return s;
    },
  };
}

export function memProvider(models: Record<string, RawModel>, texts: Record<string, string> = {}): ModelProvider {
  return {
    async json(loc) { return models[`${loc.ns}:${loc.path}`] ?? null; },
    async text(loc) { return texts[`${loc.ns}:${loc.path}`] ?? null; },
  };
}

export async function bakeById(models: Record<string, RawModel>, id: string, rot: ModelRot = NO_ROT, sprites: SpriteSource = spriteSource(), texts: Record<string, string> = {}): Promise<BakedModel> {
  const store = new ModelStore(memProvider(models, texts));
  const m = await store.load(id);
  return bakeModel(m, rot, sprites);
}

