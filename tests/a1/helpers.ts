/** A renderer that runs entirely offline: models/blockstates from memory, textures generated by name. */
export function offlineRenderer(models: Record<string, RawModel>, blockstates: Record<string, unknown>, opts: { shadeInColor?: boolean } = {}) {
  const atlas = new Atlas({
    size: 256,
    loader: async (id) => {
      const path = id.split(':')[1];
      const px = new Uint8ClampedArray(16 * 16 * 4);
      for (let i = 0; i < 256; i++) {
        px[i * 4] = 120; px[i * 4 + 1] = 120; px[i * 4 + 2] = 120;
        px[i * 4 + 3] = /translucent|ice/.test(path) ? 128 : /glass|leaves|cutout/.test(path) ? (i % 3 === 0 ? 0 : 255) : 255;
      }
      return { data: { width: 16, height: 16, data: px }, meta: null };
    },
  });
  const renderer = new BlockRendererImpl({
    atlas,
    provider: memProvider(models),
    blockstateProvider: async (loc) => (blockstates[`${loc.ns}:${loc.path}`] as any) ?? null,
    shadeInColor: opts.shadeInColor,
  });
  return renderer;
}

export function lookupOf(blocks: BlockInstance[]): WorldLookup {
  const m = new Map(blocks.map((b) => [b.pos.join(','), b]));
  return { getState: (p) => m.get(p.join(','))?.state, getBlockEntity: (p) => m.get(p.join(',')) };
}

